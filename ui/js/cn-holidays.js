/** 查询某天的节假日信息；无数据返回 null。month 从 0 起始（与 Date.getMonth() 一致）。 */
export function holidayFor(year, month, day) {
  const y = HOLIDAYS[String(year)];
  if (!y) return null;
  const md =
    (month + 1 < 10 ? "0" + (month + 1) : String(month + 1)) + "-" + (day < 10 ? "0" + day : String(day));
  return y[md] || null;
}
